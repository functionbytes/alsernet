/**
 * Recorre recursivamente todas las categorías (activas/inactivas) desde un padre
 * y devuelve SOLO las inactivas con sus URLs en TODOS los idiomas disponibles.
 *
 * Estructura de retorno:
 * [
 *   [
 *     'id_category' => int,
 *     'id_parent'   => int,
 *     'langs'       => [
 *        [
 *          'id_lang'  => int,
 *          'iso_code' => string,
 *          'name'     => string,   // nombre de la categoría en ese idioma
 *          'url'      => string,   // URL de la categoría en ese idioma
 *        ],
 *        ...
 *     ],
 *   ],
 *   ...
 * ]
 *
 * @param  int  $idParent  ID de la categoría padre.
 * @param  int|null  $idShop  ID de tienda (Por defecto, la del contexto).
 * @param  bool  $includeParentIfInactive  Incluir el padre si está inactivo.
 * @param  bool  $onlyActiveLangs  true => solo idiomas activos; false => todos.
 * @return array<int, array{
 *   id_category:int,
 *   id_parent:int,
 *   langs: array<int, array{id_lang:int, iso_code:string, name:string, url:string}>
 * }>
 */
function getInactiveCategoryUrlsDeepWithLangs(
    int $idParent,
    ?int $idShop = null,
    bool $includeParentIfInactive = false,
    bool $onlyActiveLangs = true
): array {
    $ctx = Context::getContext();
    $link = new Link;
    $idShop = $idShop ?? (int) $ctx->shop->id;

    // Idiomas disponibles (activos Por defecto)
    $languages = Language::getLanguages($onlyActiveLangs, $idShop);
    // Normalizamos un pequeño índice iso por id_lang (útil para rellenar el campo iso_code)
    $isoByLang = [];
    foreach ($languages as $lg) {
        $isoByLang[(int) $lg['id_lang']] = isset($lg['iso_code']) ? (string) $lg['iso_code'] : '';
    }

    $out = [];
    $visited = [];

    // Helper para construir bloque de langs para una categoría dada
    $buildLangs = function (int $idCategory) use ($languages, $idShop, $isoByLang): array {
        $rows = [];
        foreach ($languages as $lg) {
            $idLang = (int) $lg['id_lang'];
            $catTr = new Category($idCategory, $idLang, $idShop);
            if (! Validate::isLoadedObject($catTr)) {
                continue;
            }
            $rows[] = [
                'id_lang' => $idLang,
                'iso_code' => $isoByLang[$idLang] ?? '',
                'name' => (string) $catTr->name,
                'url' => '/'.$catTr->category_url_path, // $link->getCategoryLink($catTr, $idLang, $idShop),
            ];
        }

        return $rows;
    };

    // Opcional: incluir el padre si está inactivo
    if ($includeParentIfInactive) {
        $parentObj = new Category($idParent, (int) $ctx->language->id, $idShop);
        if (Validate::isLoadedObject($parentObj) && (int) $parentObj->active !== 1) {
            $out[] = [
                'id_category' => (int) $parentObj->id,
                'id_parent' => (int) $parentObj->id_parent,
                'langs' => $buildLangs((int) $parentObj->id),
            ];
        }
    }

    // DFS: atravesamos todos los hijos (activos e inactivos)
    $stack = [$idParent];

    while (! empty($stack)) {
        $parentId = array_pop($stack);

        // Traer TODOS los hijos (sin filtrar por activos)
        $children = Category::getChildren($parentId, (int) $ctx->language->id, false, $idShop);
        if (empty($children)) {
            continue;
        }

        foreach ($children as $child) {
            $idCat = (int) $child['id_category'];
            if (isset($visited[$idCat])) {
                continue;
            }
            $visited[$idCat] = true;

            // Siempre seguir bajando
            $stack[] = $idCat;

            $catObj = new Category($idCat, (int) $ctx->language->id, $idShop);
            if (! Validate::isLoadedObject($catObj)) {
                continue;
            }

            // Solo INACTIVAS
            if ((int) $catObj->active !== 1) {
                $out[] = [
                    'id_category' => $idCat,
                    'id_parent' => (int) $catObj->id_parent,
                    'langs' => $buildLangs($idCat),
                ];
