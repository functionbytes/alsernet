// Función recursiva para desactivar las categorías en la rama
function desactivarCategoriaYDescendientes($categoriaId)
{

    $category = new Category($categoriaId);
    $todosHijosInactivos = true;
    $tiene_productos_activos = tieneProductosActivos($categoriaId);

    // Verificar si tiene hijos y si todos los hijos están inactivos
    $sql = "SELECT id_category FROM aalv_category WHERE id_parent = $categoriaId";
    $hijos = Db::getInstance()->executeS($sql);

    // Comprobar cada hijo (subcategoría) para asegurarse de que todos estén inactivos
    if ($hijos) {
        foreach ($hijos as $hijo) {
            // Llamada recursiva para verificar los descendientes de cada hijo
            desactivarCategoriaYDescendientes($hijo['id_category']);

            // Verificar si el hijo tiene productos activos o si no se pudo desactivar
            if (tieneProductosActivos($hijo['id_category'])) {
                $todosHijosInactivos = false;
            }
        }
    }


    // Si todos los hijos ya fueron desactivados y no hay productos activos, desactivar esta categoría
    if ($todosHijosInactivos && !tieneProductosActivos($categoriaId)) {
        Db::getInstance()->executeS("UPDATE aalv_category SET active = 0 WHERE id_category = $categoriaId");
        echo "Categoría $categoriaId desactivada con éxito.\n";
    } else {
        Db::getInstance()->executeS("UPDATE aalv_category SET active = 1 WHERE id_category = $categoriaId");
        echo "No se puede desactivar la categoría $categoriaId porque tiene hijos activos.\n";
    }


}

