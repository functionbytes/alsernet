function urlPath($lue, $id_lang, $id_category = '', $product_url = NULL)
{

    $link = new Link();
    $dato_visible = explode("_", $lue);
    $lue = $dato_visible[0];
    if ($product_url) {
        $product = new Product($lue);
        $url = $link->getProductLink($lue, NULL, NULL, NULL, $id_lang);
        $name = $product->name[$id_lang];
    } else {
        $category = new Category($lue, $id_lang);
        $url = $link->getCategoryLink($lue, NULL, $id_lang);
        $extra = [];
        if ($lue == $id_category && $lue) {
            $extra = [
                1 => ' (Ver todos)',
                2 => ' (See all)',
                3 => ' (Voir tous)',
                4 => ' (Ver todos)',
                5 => ' (Alles sehen)',
                6 => ' (Scopri di più)',
            ];
        } elseif (count($dato_visible) > 2 && $dato_visible [2] == "SEL") {
            $extra = [
                1 => ' (Ver selección)',
                2 => ' (View selection)',
                3 => ' (Voir la sélection)',
                4 => ' (Ver seleção)',
                5 => ' (Auswahl ansehen)',
                6 => ' (Vedi Selezione)',
            ];

        } elseif (!$category->active) {
            $dato_visible[1] = "0";
        }
        $name = $category->name . $extra[$id_lang];
    }

    // Usa parse_url para extraer el dominio
    $url = parse_url($url);

    return [
        "title" => $name,
        "url" => $url['path'],
        "visible" => $dato_visible[1]
    ];

}

function subcategorie($value, $id_lang, $counter)
{

    $dat = '';
    $datos_items_category = [];

    if (is_array($value['items_category'])) {
        $items_category = explode(",", $value['items_category'][$id_lang]);
        foreach ($items_category as $lue) {
            $datos_items_category[] = urlPath($lue, $id_lang, $value['id_category']);
        }
    } else {
        $items_product = explode(",", $value['items_product'][$id_lang]);

        foreach ($items_product as $lue) {
            $datos_items_category[] = urlPath($lue, $id_lang, $value['id_category'], true);
        }
    }

    // Verifica si hay un título multilingüe
    if (isset($value['title']) && is_array($value['title'])) {
        if (isset($value['title'][$id_lang])) {
            // Título específico del idioma
            $name = ucfirst($value['title'][$id_lang]);
        } else {
            // Si no hay un título específico para el idioma, usa el primer título disponible
            $name = ucfirst(reset($value['title']));
        }
    } elseif (!empty($value['title'])) {
        // Si el título no es multilingüe, úsalo directamente
        $name = ucfirst($value['title']);
    } else {
        // Si no hay título proporcionado, obtén el nombre de la categoría
        $category = new Category($value['id_category'], $id_lang);
        $name = ucfirst($category->name);
    }

    $dat = [
        "title" => $name,
        "action" => '',
        "type" => "subcategorie",
        "id" => $counter,
        "column" => $value['column'],
        "position_category" => $value['position_category'],
        "position" => $value['position'],
        "items" => $datos_items_category
    ];

    return $dat;
}

function generateSubcategoryJson($categories, $langs)
{
    foreach ($langs as $lang) {

        $counter = 1;
        $array = [];

        foreach ($categories as $category) {

            $id_padre = $category['id_padre'];

            foreach ($category['subcategories'] as $key => $value) {
                if ($value['items_category'][$lang['id_lang']] || $value['items_product'][$lang['id_lang']]) {
                    $array[] = subcategorie($value, $lang['id_lang'], $counter);
                    $counter++;
                }

            }

            $ruta = 'json/' . $lang['iso_code'] . '/' . $id_padre . '/subcategory.json';
            $ruta_padre = 'json/' . $lang['iso_code'] . '/' . $id_padre;


            if (!is_dir($ruta_padre)) {
                @mkdir($ruta_padre, 7777, true);
            }

            $jsonDatos = json_encode($array, JSON_PRETTY_PRINT);

            if (!file_put_contents($ruta, $jsonDatos)) {
                echo "Ha ocurrido un error al crear/sobrescribir el archivo JSON.";
            }
            $array = [];
        }
    }


    echo "LISTO";

}

generateSubcategoryJson($categories, $langs);
